def app_in_foreground():
    """True if the foreground window belongs to this program."""
    process = wintypes.DWORD()
    user32.GetWindowThreadProcessId(user32.GetForegroundWindow(), ctypes.byref(process))
    return process.value == os.getpid()


def send_neutral_key():
    user32.keybd_event(NEUTRAL_KEY, 0, 0, OWN_MARK)
    user32.keybd_event(NEUTRAL_KEY, 0, 2, OWN_MARK)  # 2 = key up


def system_language():
    """Two-letter code of the Windows display language, for the languages known here."""
    return {0x09: "en", 0x10: "it"}.get(kernel32.GetUserDefaultUILanguage() & 0x3FF, "en")


def key_character(vk):
    """The character printed on a key in the current keyboard layout, or an empty string."""
    code = user32.MapVirtualKeyW(vk, 2) & 0xFFFF
    return chr(code).lower() if code else ""


def altgr_keys():
    """Keys that type a character together with AltGr in the current layout: (key, needs Shift) pairs."""
    layout = user32.GetKeyboardLayout(0)
    found = []
    for needs_shift in (False, True):
        state = bytearray(256)
        # Ctrl, Alt, left Ctrl, right Alt and optionally Shift
        for vk in (0x11, 0x12, 0xA2, 0xA5) + ((0x10, 0xA0) if needs_shift else ()):
            state[vk] = 0x80
        for vk in range(0x20, 0xFF):
            if 0x60 <= vk <= 0x6F or vk == 0xE7:  # numeric keypad and the placeholder key for Unicode
                continue
            text = ctypes.create_unicode_buffer(8)
            # Flag 4 reads the layout without changing the keyboard state.
            n = user32.ToUnicodeEx(vk, user32.MapVirtualKeyW(vk, 0), bytes(state), text, len(text), 4, layout)
            if n and text.value and text.value[0].isprintable():
                found.append((vk, needs_shift))
    return found


class KeyboardHook:
    """WH_KEYBOARD_LL hook.

    Every key ends up in `events` as (vk, pressed, injected, from_powertoys, swallowed, physical).
    `swallowed` is True when a later hook (PowerToys) blocked it: Windows does not receive it, but it
    is the key actually pressed on the keyboard. `physical` is the last real key received: PowerToys
    sends the converted key while that one is still being processed.

    While `capture` is True, physical keys go to `captured` and stop there.
    The last installed hook is called first, so restart() puts this one before PowerToys.
    """

    def __init__(self):
        self.events = queue.SimpleQueue()
        self.captured = queue.SimpleQueue()
        self.capture = False
        self._held = set()
        self._physical = None
        self._in_altgr = False  # the fake AltGr Ctrl is being processed
        self._thread = None
        self._thread_id = None

    def start(self):
        ready = threading.Event()
        failure = []
        self._thread = threading.Thread(target=self._run, args=(ready, failure), daemon=True)
        self._thread.start()
        if not ready.wait(5) or failure:
            self._thread = None
            raise PlatformError("error.keyboard_hook", detail=failure[0] if failure else "timeout")

    def stop(self):
        if self._thread:
            user32.PostThreadMessageW(self._thread_id, WM_QUIT, 0, 0)
            self._thread.join(5)
            self._thread = None

    def restart(self):
        self.stop()
        self.start()

    def _should_swallow(self, vk, scan, flags, pressed):
        if flags & INJECTED:
            return False
        if not pressed:
            # A release is swallowed only if its press was.
            if vk in self._held:
                self._held.discard(vk)
                return True
            return False
        if vk in self._held:  # auto repeat
            return True
        if not (self.capture and app_in_foreground()):
            return False
        self._held.add(vk)
        if scan != FAKE_ALTGR_SCAN:
            self.captured.put(vk)
        return True

    def _run(self, ready, failure):
        # Windows calls the hook only if the thread installing it processes messages.
        def procedure(code, message, address):
            if code != 0:
                return user32.CallNextHookEx(None, code, message, address)
            try:
                info = KBDLLHOOKSTRUCT.from_address(address)
                vk, scan, flags, extra = info.vkCode, info.scanCode, info.flags, info.dwExtraInfo
                pressed = message in (WM_KEYDOWN, WM_SYSKEYDOWN)
                if self._should_swallow(vk, scan, flags, pressed):
                    return 1
                injected = bool(flags & INJECTED)
                if not injected and pressed and scan != FAKE_ALTGR_SCAN:
                    self._physical = vk
            except Exception as error:  # an error must never block the keyboard
                print(f"Keyboard hook error: {error}")
                return user32.CallNextHookEx(None, code, message, address)
            fake = scan == FAKE_ALTGR_SCAN
            if fake:
                self._in_altgr = True
            try:
                result = user32.CallNextHookEx(None, code, message, address)
            finally:
                if fake:
                    self._in_altgr = False
            from_powertoys = injected and bool(extra & POWERTOYS_MARK)
            # The conversion of the fake AltGr Ctrl does not match any pressed key: it is not reported.
            hidden = fake or (self._in_altgr and from_powertoys and pressed)
            # 0xFF is a placeholder key used by PowerToys.
            if extra != OWN_MARK and not hidden and vk not in (NEUTRAL_KEY, 0xFF):
                self.events.put((vk, pressed, injected, from_powertoys, result != 0, self._physical))
            return result

        callback = HOOKPROC(procedure)
        message = wintypes.MSG()
        user32.PeekMessageW(ctypes.byref(message), None, 0, 0, 0)  # creates the message queue
        self._thread_id = kernel32.GetCurrentThreadId()
        hook = user32.SetWindowsHookExW(WH_KEYBOARD_LL, callback, kernel32.GetModuleHandleW(None), 0)
        if not hook:
            failure.append(ctypes.WinError(ctypes.get_last_error()))
            ready.set()
            return
        ready.set()
        try:
            while user32.GetMessageW(ctypes.byref(message), None, 0, 0) > 0:
                pass
        finally:
            user32.UnhookWindowsHookEx(hook)


# --- PowerToys ---------------------------------------------------------------

SYSTEM32 = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32"
ENGINE = "powertoys.keyboardmanagerengine.exe"
RELOAD_EVENT = "PowerToys_KeyboardManager_Event_Settings"  # tells the engine to read the mapping again
EMPTY_KEYMAP = {"remapKeys": {"inProcess": []}, "remapKeysToText": {"inProcess": []},
                "remapShortcuts": {"global": [], "appSpecific": []},
                "remapShortcutsToText": {"global": [], "appSpecific": []}}
NEW_MODULE_SETTINGS = {"properties": {"activeConfiguration": {"value": "default"},
                                      "keyboardConfigurations": {"value": ["default"]}},
                       "name": "Keyboard Manager", "version": "1.0"}


def _run_tool(program, *arguments):
    return subprocess.run([str(SYSTEM32 / program), *arguments], capture_output=True, text=True,
                          errors="replace", creationflags=subprocess.CREATE_NO_WINDOW, check=False)


def _processes():
    """Lower-case names of the running programs."""
    result = _run_tool("tasklist.exe", "/fo", "csv", "/nh")
    result.check_returncode()
    return {r[0].lower() for r in csv.reader(result.stdout.splitlines()) if len(r) > 1}


def _kill(name):
    # It can fail if the process has already exited: the caller checks the list again.
    _run_tool("taskkill.exe", "/f", "/im", name)


def _wait_for(condition, seconds):
    end = time.monotonic() + seconds
    while not condition():
        if time.monotonic() > end:
            return False
        time.sleep(0.5)
    return True


def _read_json(file):
    return json.loads(file.read_text(encoding="utf-8-sig"))


def _write_json(file, data):
    """Writes a temporary file and renames it, so a file is never left half written."""
    file.parent.mkdir(parents=True, exist_ok=True)
    temporary = file.with_name(file.name + ".tmp")
    temporary.write_text(json.dumps(data, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")
    os.replace(temporary, file)


@contextmanager
def _clean_child_environment():
    """Keeps the temporary folder of the exe away from the programs started here.

    They would inherit it as a place to load libraries from, and PowerToys keeps running after this
    program has closed and deleted that folder.
    """
    folder = getattr(sys, "_MEIPASS", None)  # set only inside the exe
    if not folder:
        yield
        return
    saved = {name: os.environ.pop(name) for name in ("TCL_LIBRARY", "TK_LIBRARY") if name in os.environ}
    kernel32.SetDllDirectoryW(None)
    try:
        yield
    finally:
        kernel32.SetDllDirectoryW(folder)
        os.environ.update(saved)


def _signal_reload():
    event = kernel32.OpenEventW(0x0002, False, RELOAD_EVENT)  # EVENT_MODIFY_STATE
    if not event:
        return False
    try:
        return bool(kernel32.SetEvent(event))
    finally:
        kernel32.CloseHandle(event)


class PowerToys:
    def __init__(self):
        base = Path(os.environ["LOCALAPPDATA"]) / "Microsoft" / "PowerToys"
        self.folder = base / "Keyboard Manager"
        self.general_settings = base / "settings.json"
        self.module_settings = self.folder / "settings.json"
        self.editor_settings = self.folder / "editorSettings.json"
        self.backup = self.folder / "backup-mac-keyboard"

    def executable(self):
        for variable in ("ProgramFiles", "LOCALAPPDATA"):
            base = os.environ.get(variable)
            if base and (file := Path(base) / "PowerToys" / "PowerToys.exe").is_file():
                return file
        return None

    def engine_running(self):
        return ENGINE in _processes()

    def mapping_file(self):
        """File of the active Keyboard Manager configuration (usually default.json)."""
        name = None
        if self.module_settings.is_file():
            settings = _read_json(self.module_settings)
            name = settings.get("properties", {}).get("activeConfiguration", {}).get("value")
        return self.folder / f"{name or 'default'}.json"

    def current_mapping(self):
        """The mapping Keyboard Manager is applying right now (empty if it is off)."""
        try:
            enabled = _read_json(self.general_settings)["enabled"]["Keyboard Manager"] is True
            if not enabled or not self.engine_running():
                return EMPTY_KEYMAP
            file = self.mapping_file()
            return _read_json(file) if file.is_file() else EMPTY_KEYMAP
        except (OSError, ValueError, KeyError, TypeError, AttributeError):
            return EMPTY_KEYMAP

    def _close(self):
        def closed():
            names = {n for n in _processes() if n.startswith("powertoys")}
            for name in names:
                _kill(name)
            return not names

        if not _wait_for(closed, 10):
            raise PlatformError("error.powertoys_close")

    def _launch(self):
        file = self.executable()
        with _clean_child_environment():
            os.startfile(file, cwd=str(file.parent))

    def apply(self, keymap):
        """Writes the mapping and makes it active. Raises PlatformError if it cannot."""
        if not self.executable():
            raise PlatformError("error.powertoys_missing")
        if not self.general_settings.is_file():  # never started: let it create its settings
            self._launch()
            if not _wait_for(self.general_settings.is_file, 60):
                raise PlatformError("error.powertoys_settings")
            time.sleep(5)

        # The Keyboard Manager editor, if open, could overwrite the mapping.
        for name in _processes():
            if name.startswith("powertoys.keyboardmanagereditor"):
                _kill(name)

        enabled = (_read_json(self.general_settings).get("enabled") or {}).get("Keyboard Manager") is True
        if not enabled:  # PowerToys reads the general settings only at startup
            self._close()
            settings = _read_json(self.general_settings)
            settings["enabled"] = {**(settings.get("enabled") or {}), "Keyboard Manager": True}
            _write_json(self.general_settings, settings)

        if not self.module_settings.is_file():
            _write_json(self.module_settings, NEW_MODULE_SETTINGS)
        destination = self.mapping_file()

        # Backup of the situation before the first use.
        if not self.backup.is_dir():
            self.backup.mkdir(parents=True)
            for file in (destination, self.editor_settings):
                if file.is_file():
                    shutil.copyfile(file, self.backup / file.name)

        _write_json(destination, keymap)
        # The PowerToys editor rebuilds this file from the mapping.
        self.editor_settings.unlink(missing_ok=True)

        if self.engine_running() and _signal_reload():
            return
        # An empty mapping does not need anything to be restarted.
        if keymap == EMPTY_KEYMAP:
            if not enabled:
                self._launch()
            return
        self._close()
        self._launch()
        if not _wait_for(self.engine_running, 20):
            raise PlatformError("error.engine_not_running")
        time.sleep(1)  # the engine installs its hook shortly after starting
