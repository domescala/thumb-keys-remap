user32 = ctypes.WinDLL("user32", use_last_error=True)
kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)

WH_KEYBOARD_LL = 13
WM_KEYDOWN, WM_SYSKEYDOWN, WM_QUIT = 0x0100, 0x0104, 0x0012
INJECTED = 0x10  # key generated by a program, not by the keyboard
FAKE_ALTGR_SCAN = 0x21D  # "virtual" Ctrl that Windows adds to AltGr
NEUTRAL_KEY = 0xE8  # unassigned key: stops Win or Alt alone from opening Start or the window menu
OWN_MARK = 0x4D41434B  # identifies the keys sent by this program
POWERTOYS_MARK = 0x1  # bit set on the keys generated by Keyboard Manager


class PlatformError(Exception):
    """An error to show to the user: `key` is a text identifier of the locale files."""

    def __init__(self, key, **values):
        super().__init__(key)
        self.key, self.values = key, values


class KBDLLHOOKSTRUCT(ctypes.Structure):
    _fields_ = [("vkCode", wintypes.DWORD), ("scanCode", wintypes.DWORD), ("flags", wintypes.DWORD),
                ("time", wintypes.DWORD), ("dwExtraInfo", ctypes.c_size_t)]


HOOKPROC = ctypes.WINFUNCTYPE(wintypes.LPARAM, ctypes.c_int, wintypes.WPARAM, wintypes.LPARAM)


def _declare(function, result, *arguments):
    function.restype = result
    function.argtypes = arguments


